def _bars(s):
    return [s[i:i + 4] for i in range(0, len(s), 4)]


def solve(name, clue, memory):
    try:
        pat, _, nt = clue.partition("/")
        try:
            num = int(nt)
        except Exception:
            num = 5
        rests = [i for i in range(len(pat)) if pat[i] == "."]
        nr = len(rests)
        sil = TABLE.get("%d_%d" % (num, nr))
        if sil is None:
            sil = FALLBACK.get(num, 3)
        sil = max(0, min(sil, nr))
        out = ["." if c == "x" else "x" for c in pat]
        if sil:
            step = nr / sil
            for j in range(sil):
                out[rests[int((j + 0.5) * step) % nr]] = "."
        bb = _bars(pat)
        head = "   |" + "|".join("1234"[:len(b)] for b in bb) + "|"
        return (head + "\nbd |" + "|".join(bb) + "|"
                + "\nsn |" + "|".join(_bars("".join(out))) + "|")
    except Exception:
        return None
